import { describe, expect, test } from 'vitest';

import {
  createDraftTitleCodec,
  getDeletionGroup,
  getPullRequestDescription,
  parseRestFiles,
  PULL_REQUEST_DESCRIPTION,
  setDeletionGroup,
} from '$lib/services/backends/git/shared/pull-requests';

describe('shared pull request constants', () => {
  test('describes a request as one the CMS opened', () => {
    expect(PULL_REQUEST_DESCRIPTION).toBe('Automatically generated by Sveltia CMS');
  });
});

describe('deletion group record', () => {
  const RECORD = '<!-- sveltia-cms:deletion-group=group-1 -->';

  test('adds the record to the description only for a deletion group', () => {
    expect(getPullRequestDescription()).toBe(PULL_REQUEST_DESCRIPTION);
    expect(getPullRequestDescription('group-1')).toBe(`${PULL_REQUEST_DESCRIPTION}\n\n${RECORD}`);
  });

  /**
   * Get the deletion group recorded in the given description.
   * @param {string | undefined} description Description.
   * @returns {string | undefined} Deletion group ID.
   */
  const read = (description) => getDeletionGroup(/** @type {any} */ ({ number: 1, description }));

  test('reads the group back from the description', () => {
    expect(read(getPullRequestDescription('group-1'))).toBe('group-1');
    expect(read(PULL_REQUEST_DESCRIPTION)).toBeUndefined();
    expect(read('')).toBeUndefined();
    // An Open Authoring draft, which has no pull request to carry a description
    expect(read(undefined)).toBeUndefined();
    // Anything but a plain ID isn’t taken as one
    expect(read('<!-- sveltia-cms:deletion-group=a b -->')).toBeUndefined();
  });

  test('reads the first record of a description carrying more than one', () => {
    expect(read(`Edited\n\n${RECORD}\n\n<!-- sveltia-cms:deletion-group=group-2 -->`)).toBe(
      'group-1',
    );
  });

  test('replaces the record, keeping the rest of the description', () => {
    expect(setDeletionGroup('Edited', 'group-2')).toBe(
      'Edited\n\n<!-- sveltia-cms:deletion-group=group-2 -->',
    );
    expect(setDeletionGroup(`Edited\n\n${RECORD}`, 'group-2')).toBe(
      'Edited\n\n<!-- sveltia-cms:deletion-group=group-2 -->',
    );
    expect(setDeletionGroup(`Edited\n\n${RECORD}`, undefined)).toBe('Edited');
    expect(setDeletionGroup('', 'group-1')).toBe(RECORD);
    expect(setDeletionGroup('', undefined)).toBe('');
  });

  test('removes every record, along with the blank lines before it', () => {
    const description = `Edited\n\n${RECORD}\n\n<!-- sveltia-cms:deletion-group=group-2 -->`;

    expect(setDeletionGroup(description, undefined)).toBe('Edited');
    expect(setDeletionGroup(description, 'group-3')).toBe(
      'Edited\n\n<!-- sveltia-cms:deletion-group=group-3 -->',
    );
  });
});

describe('createDraftTitleCodec', () => {
  const { strip, format } = createDraftTitleCodec({
    regex: /^\s*(?:\[draft\]|draft:)\s*/i,
    prefix: 'Draft: ',
  });

  test.each([
    ['Draft: Title', 'Title'],
    ['  [Draft]  Draft: Title', 'Title'],
    ['Drafting notes', 'Drafting notes'],
    ['Title', 'Title'],
  ])('strips the draft indicators from %j', (input, expected) => {
    expect(strip(input)).toBe(expected);
  });

  test('adds the prefix only to a draft', () => {
    expect(format('Title', true)).toBe('Draft: Title');
    expect(format('Title', false)).toBe('Title');
  });
});

describe('parseRestFiles', () => {
  test('converts the REST files to workflow files with the previous path of a rename', () => {
    expect(
      parseRestFiles(
        [
          { filename: 'a.md', status: 'added', patch: '@@' },
          { filename: 'b.md', status: 'removed' },
          { filename: 'new.md', status: 'renamed', previous_filename: 'old.md' },
        ],
        { removedStatus: 'removed' },
      ),
    ).toEqual([
      { path: 'a.md', sha: '', size: 0, deleted: false, previousPath: undefined },
      { path: 'b.md', sha: '', size: 0, deleted: true, previousPath: undefined },
      { path: 'new.md', sha: '', size: 0, deleted: false, previousPath: 'old.md' },
    ]);
  });

  test('takes the service’s status for a removed file and an empty previous path as none', () => {
    expect(
      parseRestFiles(
        [
          { filename: 'a.md', status: 'deleted', previous_filename: '' },
          { filename: 'b.md', status: 'removed', previous_filename: '' },
        ],
        { removedStatus: 'deleted' },
      ),
    ).toEqual([
      { path: 'a.md', sha: '', size: 0, deleted: true, previousPath: undefined },
      { path: 'b.md', sha: '', size: 0, deleted: false, previousPath: undefined },
    ]);
  });
});
