  beforeEach(() => {
    vi.mocked(fetchAPI).mockResolvedValue({});
  });

  const pullRequest = { number: 7, branch: 'cms/posts/hello', title: 'Hello' };
  const repository = { owner: 'owner', repo: 'repo' };

