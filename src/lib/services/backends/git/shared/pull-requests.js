/**
 * @import { CommitAuthor, WorkflowFile, WorkflowPullRequest } from '$lib/types/private';
 */

/**
 * Description the CMS opens an Editorial Workflow pull request or merge request with, which tells a
 * maintainer where it came from.
 */
export const PULL_REQUEST_DESCRIPTION = 'Automatically generated by Sveltia CMS';

/**
 * Regular expression matching the record of the deletion group a pull request belongs to, along
 * with the blank lines before it. The record is an HTML comment, which the services leave out of
 * the rendered description. It’s global, so {@link setDeletionGroup} removes every record.
 */
const DELETION_GROUP_REGEX = /\s*<!-- sveltia-cms:deletion-group=([\w-]+) -->/g;
/**
 * Regular expression matching the first record of the deletion group a pull request belongs to,
 * for {@link getDeletionGroup}. Unlike {@link DELETION_GROUP_REGEX}, it’s not global, so `match()`
 * gives the captured group ID.
 */
const DELETION_GROUP_RECORD_REGEX = /<!-- sveltia-cms:deletion-group=([\w-]+) -->/;

/**
 * Get the record of the given deletion group, to be added to a pull request description.
 * @param {string} deletionGroup Deletion group ID.
 * @returns {string} Record.
 */
const formatDeletionGroup = (deletionGroup) =>
  `<!-- sveltia-cms:deletion-group=${deletionGroup} -->`;

/**
 * Get the description the CMS opens an Editorial Workflow pull request or merge request with,
 * along with the record of the deletion group it belongs to, if any.
 * @param {string} [deletionGroup] Deletion group ID, if any. See {@link getDeletionGroup}.
 * @returns {string} Description.
 */
export const getPullRequestDescription = (deletionGroup) =>
  deletionGroup
    ? `${PULL_REQUEST_DESCRIPTION}\n\n${formatDeletionGroup(deletionGroup)}`
    : PULL_REQUEST_DESCRIPTION;

/**
 * Get the deletion group recorded in the description of the given pull request: the ID of the
 * selection of entries it was opened with to delete. Each entry of a selection gets its own pull
 * request, and the references to the whole selection are removed in every one of them, so they
 * have to be told apart from the pull requests deleting other entries of the same collection one
 * at a time.
 * @param {WorkflowPullRequest} pullRequest Pull request.
 * @returns {string | undefined} Deletion group ID, or `undefined` for a pull request deleting an
 * entry on its own, or not deleting one at all.
 */
export const getDeletionGroup = ({ description }) =>
  description?.match(DELETION_GROUP_RECORD_REGEX)?.[1];

/**
 * Record the given deletion group in a pull request description, replacing any group recorded
 * before, or remove the record. The rest of the description, which a maintainer may have edited,
 * is kept as it is.
 * @param {string} description Current description.
 * @param {string | undefined} deletionGroup Deletion group ID, or `undefined` to remove the record.
 * @returns {string} New description.
 */
export const setDeletionGroup = (description, deletionGroup) => {
  const text = description.replace(DELETION_GROUP_REGEX, '');

  return deletionGroup
    ? [text, formatDeletionGroup(deletionGroup)].filter(Boolean).join('\n\n')
    : text;
};

/**
 * Create helpers for a title that marks a pull request or merge request as a draft with a prefix,
 * as Gitea/Forgejo and GitLab do in place of a dedicated API field.
 * @param {object} args Arguments.
 * @param {RegExp} args.regex Regular expression matching one draft indicator at the beginning of a
 * title, along with the whitespace around it. It must not have the `g` or `y` flag.
 * @param {string} args.prefix Prefix added to a title to mark it as a draft.
 * @returns {{
 * strip: (title: string) => string,
 * format: (title: string, isDraft: boolean) => string,
 * }} `strip` removes any draft indicator from a raw title; `format` adds the prefix to a title
 * without one if `isDraft` is `true`.
 */
export const createDraftTitleCodec = ({ regex, prefix }) => ({
  /**
   * Remove any draft indicator from the given title.
   * @param {string} title Raw title.
   * @returns {string} Title without a draft prefix.
   */
  strip: (title) => {
    let result = title;

    // Repeat, because a title can carry a combination of indicators, e.g. `Draft: [Draft] Title`
    while (regex.test(result)) {
      result = result.replace(regex, '');
    }

    return result;
  },
  /**
   * Add the draft prefix to the given title if the request is a draft.
   * @param {string} title Title without a draft prefix.
   * @param {boolean} isDraft Whether the request is a draft.
   * @returns {string} Title to send to the API.
   */
  format: (title, isDraft) => (isDraft ? `${prefix}${title}` : title),
});

/**
 * Convert the changed files of a pull request or comparison, as listed by the REST API of GitHub or
 * Gitea/Forgejo, to workflow files.
 * @param {Record<string, any>[]} files Files.
 * @param {object} args Arguments.
 * @param {string} args.removedStatus Status the service gives a removed file: `removed` on GitHub,
 * `deleted` on Gitea/Forgejo.
 * @returns {WorkflowFile[]} Files.
 */
export const parseRestFiles = (files, { removedStatus }) =>
  files.map(({ filename, status, previous_filename: previousPath }) => ({
    path: filename,
    sha: '',
    size: 0,
    deleted: status === removedStatus,
    // Gitea/Forgejo gives a file that wasn’t renamed an empty previous path
    previousPath: previousPath || undefined,
  }));

/**
 * Convert the user who opened a pull request or merge request to a commit author. An empty display
 * name falls back to the user name, like a missing one.
 * @param {object} user User.
 * @param {string} [user.login] User name.
 * @param {string | null} [user.name] Display name.
 * @param {string | null} [user.email] Email address.
 * @param {number} [user.id] User ID.
 * @returns {CommitAuthor | undefined} Author, or `undefined` if the user is unknown.
 */
export const toCommitAuthor = ({ login, name, email, id }) =>
  login ? { name: name || login, email: email ?? '', id, login } : undefined;

/**
 * Parse a pull request returned by the REST API of GitHub or Gitea/Forgejo, taking the properties
 * the two services give differently from the caller.
 * @param {Record<string, any>} item Pull request.
 * @param {Pick<WorkflowPullRequest, 'title' | 'branch' | 'status' | 'author' | 'description'> &
 * Partial<WorkflowPullRequest>} overrides Properties to add or override.
 * @returns {WorkflowPullRequest} Parsed pull request.
 */
export const parseRestPullRequest = (item, overrides) => ({
  number: item.number,
  nodeId: String(item.id),
  url: item.html_url,
  headSHA: item.head?.sha,
  createdDate: new Date(item.created_at),
  updatedDate: new Date(item.updated_at),
  files: [],
  ...overrides,
});
